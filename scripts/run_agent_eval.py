#!/usr/bin/env python3
"""Tasks 7.1-7.4 -- run the langgraph plan/critique/answer agent over the
golden set's `multi_hop`/`yoy_metric`/`year_collision`-tagged items (plus
`gq-003`, to confirm the citation-repair path) and write
`evals/phase2_baseline.md`, directly comparable to `evals/phase1_baseline.md`.

Usage: .venv/bin/python scripts/run_agent_eval.py
"""

from __future__ import annotations

import json
import time

from hfx_portgraph.agent import run_agent
from hfx_portgraph.paths import GOLDEN_PATH, ROOT

ITEM_IDS = [
    "gq-001",  # flagship, multi_hop/yoy_metric
    "gq-003",  # answer_uncited citation-repair re-check
    "gq-004",
    "gq-007",
    "gq-010",
    "gq-012",
    "gq-014",
    "gq-017",
    "gq-019",  # year_collision
    "gq-020",  # year_collision
    "gq-022",
    "gq-024",
    "gq-025",
]

OUT_PATH = ROOT / "evals" / "phase2_baseline.md"
SCRATCH_PATH = ROOT / "scripts" / "scratch" / "phase2_agent_eval.json"


def _load_items(ids: list[str]) -> dict[str, dict]:
    wanted = set(ids)
    items = {}
    with GOLDEN_PATH.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            obj = json.loads(line)
            if obj["id"] in wanted:
                items[obj["id"]] = obj
    return items


def main() -> int:
    items = _load_items(ITEM_IDS)
    records = []
    for item_id in ITEM_IDS:
        item = items[item_id]
        start = time.time()
        result = run_agent(item["question"])
        elapsed = time.time() - start
        record = {
            "id": item_id,
            "tags": item["tags"],
            "question": item["question"],
            "expected_evidence": item["expected_evidence"],
            "status": result["status"],
            "iterations": result["iterations"],
            "plan": result["plan"],
            "num_citations": len(result["citations"]),
            "citation_report_ids": sorted({c["report_id"] for c in result["citations"] if c.get("report_id")}),
            "answer": result["answer"],
            "elapsed_seconds": round(elapsed, 1),
        }
        records.append(record)
        print(f"{item_id}: status={record['status']} iterations={record['iterations']} ({elapsed:.1f}s)")

    SCRATCH_PATH.parent.mkdir(parents=True, exist_ok=True)
    SCRATCH_PATH.write_text(json.dumps(records, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"full record: {SCRATCH_PATH}")

    report = _render_report(records)
    OUT_PATH.write_text(report, encoding="utf-8")
    print(f"wrote {OUT_PATH}")
    return 0


def _render_report(records: list[dict]) -> str:
    lines: list[str] = []
    lines.append("# Phase 2 langgraph plan/critique/answer baseline")
    lines.append("")
    lines.append(
        "**Date:** 2026-09-15\n"
        "**Status:** RUN — local Ollama (`llama3.1`, `nomic-embed-text`) reachable; existing "
        "`data/chroma/` index (983 child chunks, `strip-page-furniture` + task-prefixed "
        "embeddings) used as-is."
    )
    lines.append("")
    lines.append(
        "Direct comparison target for `evals/phase1_baseline.md`'s naive `retrieve()`/`ask()` "
        "results, generated by `scripts/run_agent_eval.py` via `hfx_portgraph.agent.run_agent()` "
        "(the `hfx-agent-ask` CLI's underlying call) — planner → retriever → critic → synthesizer "
        "loop, `max_iterations=2`, `n_results=6` per dispatch call. Full machine-readable output: "
        "`scripts/scratch/phase2_agent_eval.json`."
    )
    lines.append("")

    lines.append("## Per-item outcomes")
    lines.append("")
    lines.append("| id | tags | status | iterations | plan years | report_ids cited | notes |")
    lines.append("|---|---|---|---|---|---|---|")
    for r in records:
        tags = ", ".join(r["tags"])
        plan_years = r["plan"].get("years") or []
        cited_reports = ", ".join(r["citation_report_ids"]) or "none"
        note = _note_for(r)
        lines.append(f"| {r['id']} | {tags} | `{r['status']}` | {r['iterations']} | {plan_years} | {cited_reports} | {note} |")
    lines.append("")

    lines.append("## Flagship: gq-001 vs phase1_baseline.md")
    lines.append("")
    gq1 = next(r for r in records if r["id"] == "gq-001")
    lines.append(
        f"Phase 1: retrieval surfaced 2020/2021/2022 evidence but **missed 2023 entirely**. "
        f"Phase 2: plan covered years {gq1['plan'].get('years')}, status `{gq1['status']}`, "
        f"{gq1['num_citations']} citations across reports {gq1['citation_report_ids']}."
    )
    lines.append("")
    lines.append("Answer:")
    lines.append("")
    lines.append("```")
    lines.append(gq1["answer"])
    lines.append("```")
    lines.append("")

    lines.append("## gq-003 citation-repair re-check")
    lines.append("")
    gq3 = next(r for r in records if r["id"] == "gq-003")
    lines.append(
        f"Phase 1: `answer_uncited` — right evidence retrieved, model dropped the citation tag. "
        f"Phase 2 (with the one-shot citation-repair pass, design.md Decision 7): status "
        f"`{gq3['status']}`."
    )
    lines.append("")
    lines.append("```")
    lines.append(gq3["answer"])
    lines.append("```")
    lines.append("")

    lines.append("## year_collision items (gq-019, gq-020)")
    lines.append("")
    for iid in ("gq-019", "gq-020"):
        r = next(x for x in records if x["id"] == iid)
        lines.append(f"### {iid}")
        lines.append("")
        lines.append(f"status: `{r['status']}`, plan years: {r['plan'].get('years')}, iterations: {r['iterations']}")
        lines.append("")
        lines.append("```")
        lines.append(r["answer"])
        lines.append("```")
        lines.append("")

    ok_count = sum(1 for r in records if r["status"] == "ok")
    lines.append("## Summary")
    lines.append("")
    lines.append(
        f"{ok_count}/{len(records)} items returned `ok` (cited, non-empty) status. See "
        "`scripts/scratch/phase2_agent_eval.json` for full plans/answers/citations per item, "
        "and the per-item table above for a like-for-like comparison against "
        "`evals/phase1_baseline.md`'s table."
    )
    lines.append("")
    return "\n".join(lines)


def _note_for(r: dict) -> str:
    expected_years = set(r["expected_evidence"].get("years") or [])
    plan_years = set(r["plan"].get("years") or [])
    missing = sorted(expected_years - plan_years)
    if missing:
        return f"planner missed years {missing}"
    if r["status"] == "ok":
        return "full planned-year coverage in plan"
    return ""


if __name__ == "__main__":
    raise SystemExit(main())
